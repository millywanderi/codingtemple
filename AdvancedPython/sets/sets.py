#!/usr/bin/env python3

# Creating a Set with Values
new_set = {'one', 'two', 'three'}
print(new_set)

# Using sets to remove duplicates from other data structures.
myfruits = ["apple", "apple", "banana", "mango"]
fruits = set(myfruits)
print(fruits)

# Looping Over a Set
fruits = {"apple", "banana", "mango"}
for fruit in fruits:
    print(fruit)
