#!/usr/bin/env python3

# .count(): Returns the number of times a specified value appears in 
#the tuple
numbers = (1, 2, 3, 2, 4, 2, 6, 2)
print(numbers.count(2))

# .index(): Returns the index of the first occurrence of a specified 
#value
numbers = (1, 2, 3, 2, 4, 2, 6, 2)
print(numbers.index(6))
