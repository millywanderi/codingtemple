#!/usr/bin/env python3

# Print the second item in the tuple
mytuple = ("Steve", "Millie", "Kylie", "Lyle")
print(mytuple[1])

# Print the last item of the tuple
mytuple = ("Steve", "Millie", "Kylie", "Lyle")
print(mytuple[-1])

# Return the third, fourth, and fifth item
mytuple = (1, 2, 3, 4, 5, 6, 7, 8, 9)
print(mytuple[2:5])
